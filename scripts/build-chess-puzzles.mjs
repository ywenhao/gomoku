import { spawn } from "node:child_process";
import { createInterface } from "node:readline";
import { writeFile } from "node:fs/promises";
const source = process.argv[2];
if (!source)
  throw new Error(
    "Usage: node scripts/build-chess-puzzles.mjs <official CSV.zst> [count]",
  );
const target = Number(process.argv[3] ?? 600);
if (!Number.isInteger(target) || target < 1 || target > 3000)
  throw new Error("Invalid count");
const proc = spawn("zstd", ["-dc", "--", source], {
  stdio: ["ignore", "pipe", "inherit"],
});
const lines = createInterface({ input: proc.stdout });
const buckets = Array.from({ length: 12 }, () => []);
const quota = Math.ceil(target / buckets.length);
let count = 0;
for await (const line of lines) {
  const f = line.split(",");
  if (f.length < 10) continue;
  const [id, fen, moves, ratingS, , popularityS, playsS, themes] = f;
  const rating = Number(ratingS),
    bucket = Math.floor((rating - 700) / 125);
  if (
    !Number.isInteger(bucket) ||
    bucket < 0 ||
    bucket >= buckets.length ||
    buckets[bucket].length >= quota
  )
    continue;
  if (Number(popularityS) < 88 || Number(playsS) < 1200) continue;
  const n = moves.split(" ").length;
  if (n < 2 || n > 8 || n % 2) continue;
  if (
    !themes
      .split(" ")
      .some((t) =>
        [
          "mateIn1",
          "mateIn2",
          "mateIn3",
          "fork",
          "pin",
          "skewer",
          "discoveredAttack",
          "sacrifice",
          "endgame",
          "rookEndgame",
          "pawnEndgame",
          "queenEndgame",
          "knightEndgame",
          "bishopEndgame",
        ].includes(t),
      )
  )
    continue;
  buckets[bucket].push({ id: `lc-${id}`, fen, moves, rating, themes });
  if (++count >= quota * buckets.length) break;
}
lines.close();
proc.stdout.destroy();
proc.kill();
const rows = buckets
  .flat()
  .sort((a, b) => a.rating - b.rating)
  .slice(0, target);
await writeFile(
  "lib/data/chess-puzzles.ts",
  `/** Lichess Puzzle Database, CC0. Generated by scripts/build-chess-puzzles.mjs. */\nexport interface ChessPuzzle { id: string; fen: string; moves: string; rating: number; themes: string }\nexport const CHESS_PUZZLES: readonly ChessPuzzle[] = ${JSON.stringify(rows)};\n`,
);
console.log(
  `Generated ${rows.length} puzzles across ${buckets.filter((b) => b.length).length} rating bands`,
);
